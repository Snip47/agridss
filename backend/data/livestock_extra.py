def build_extra(base_list):
    """Return the extra livestock entries, inheriting guidance from the species entries in base_list."""
    base = {a["name"]: a for a in base_list}
    out = []
    for (name, bkey, cat, purpose, origin, sk, sv, desc, breeding, feed_note, aez) in BREED_ENTRIES:
        b = base[bkey]
        breed = {"name": name.split(" (")[0], "origin": origin, "notes": desc.split(". ")[0].rstrip(".") + "."}
        if sk and sv:
            breed[sk] = sv
        out.append({
            "name": name, "category": cat, "purpose": purpose,
            "water_requirement": b.get("water_requirement", ""), "space_required": b.get("space_required", ""),
            "suitable_aez": [aez] if aez else list(b.get("suitable_aez", [])),
            "description": desc,
            "feeding_guide": ((feed_note + " ") if feed_note else "") + b.get("feeding_guide", ""),
            "housing_requirements": b.get("housing_requirements", ""),
            "breeding_info": breeding,
            "market_info": b.get("market_info", ""),
            "common_diseases": list(b.get("common_diseases", [])),
            "vaccination_schedule": copy.deepcopy(b.get("vaccination_schedule", [])),
            "breeds": [breed],
        })
    out.extend(copy.deepcopy(CUSTOM_ENTRIES))
    return out
