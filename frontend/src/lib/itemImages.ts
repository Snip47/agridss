// Smart fuzzy image matcher
export function getCropImage(name: string): string {
  const key = name.toLowerCase().replace(/[()]/g, '').trim()
  // Exact match
  if (CROP_IMAGES[key]) return CROP_IMAGES[key]
  // Partial match
  for (const [k, v] of Object.entries(CROP_IMAGES)) {
    if (key.includes(k) || k.includes(key.split(' ')[0])) return v
  }
  return 'https://images.unsplash.com/photo-1574943320219-553eb213f72d?w=800&q=85&fit=crop'
}

export function getAnimalImage(name: string): string {
  const key = name.toLowerCase().replace(/[()]/g, '').trim()
  if (ANIMAL_IMAGES[key]) return ANIMAL_IMAGES[key]
  for (const [k, v] of Object.entries(ANIMAL_IMAGES)) {
    if (key.includes(k) || k.includes(key.split(' ')[0])) return v
  }
  return 'https://images.unsplash.com/photo-1500595046743-cd271d694d30?w=800&q=85&fit=crop'
}

export function getCatImage(category: string): string {
  return CAT_IMAGES[category.toLowerCase()] || CAT_IMAGES.cattle
}
